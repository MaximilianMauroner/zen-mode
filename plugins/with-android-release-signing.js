const { withAppBuildGradle } = require('@expo/config-plugins');

const MARKER = '// @generated by with-android-release-signing';
const DEBUG_SIGNING_LINE = 'signingConfig signingConfigs.debug';
const DEBUG_CERTIFICATE_SHA256 = 'fac61745dc0903786fb9ede62a962b399f7348f0bb6f899b8332667591033b9c';

const ENVIRONMENT_REGION = `${MARKER}: environment begin
def uploadSigningEnvironment = [
    storeFile: System.getenv("ZEN_MODE_UPLOAD_STORE_FILE")?.trim(),
    storePassword: System.getenv("ZEN_MODE_UPLOAD_STORE_PASSWORD"),
    keyAlias: System.getenv("ZEN_MODE_UPLOAD_KEY_ALIAS")?.trim(),
    keyPassword: System.getenv("ZEN_MODE_UPLOAD_KEY_PASSWORD"),
    certificateSha256: System.getenv("ZEN_MODE_UPLOAD_CERT_SHA256")?.trim(),
]
def uploadSigningValues = uploadSigningEnvironment.values()
def uploadSigningReady = uploadSigningValues.every { it }
def uploadSigningPartiallyConfigured = uploadSigningValues.any { it } && !uploadSigningReady

if (uploadSigningPartiallyConfigured) {
    throw new GradleException("Zen Mode upload signing is only partially configured. Set all five ZEN_MODE_UPLOAD_* signing variables or unset all of them.")
}

def normalizeUploadCertificateSha256 = { value ->
    value.replace(":", "").toLowerCase(java.util.Locale.ROOT)
}

def verifyUploadSigningIdentity = {
    def storePath = new File(uploadSigningEnvironment.storeFile)
    if (!storePath.isAbsolute() || !storePath.isFile()) {
        throw new GradleException("ZEN_MODE_UPLOAD_STORE_FILE must be an absolute path to an existing keystore.")
    }

    def expectedSha256 = normalizeUploadCertificateSha256(uploadSigningEnvironment.certificateSha256)
    if (!(expectedSha256 ==~ /[0-9a-f]{64}/)) {
        throw new GradleException("ZEN_MODE_UPLOAD_CERT_SHA256 must be a 64-digit SHA-256 certificate fingerprint.")
    }
    if (expectedSha256 == "${DEBUG_CERTIFICATE_SHA256}") {
        throw new GradleException("Zen Mode release artifacts cannot use the Android debug certificate.")
    }

    def storePassword = uploadSigningEnvironment.storePassword.toCharArray()
    try {
        def keyStore = java.security.KeyStore.getInstance("JKS")
        storePath.withInputStream { input -> keyStore.load(input, storePassword) }
        def certificate = keyStore.getCertificate(uploadSigningEnvironment.keyAlias)
        if (certificate == null) {
            throw new GradleException("ZEN_MODE_UPLOAD_KEY_ALIAS does not identify a certificate in the configured keystore.")
        }
        def actualSha256 = java.security.MessageDigest.getInstance("SHA-256")
            .digest(certificate.encoded)
            .collect { String.format(java.util.Locale.ROOT, "%02x", it & 0xff) }
            .join("")
        if (actualSha256 != expectedSha256) {
            throw new GradleException("The configured keystore certificate does not match ZEN_MODE_UPLOAD_CERT_SHA256.")
        }
    } catch (GradleException error) {
        throw error
    } catch (Exception error) {
        throw new GradleException("Zen Mode could not verify the configured upload keystore and certificate.", error)
    } finally {
        java.util.Arrays.fill(storePassword, (char) 0)
    }
}
${MARKER}: environment end`;
const ENVIRONMENT_BLOCK = `${ENVIRONMENT_REGION}\n\n`;

const RELEASE_SIGNING_BLOCK = `${MARKER}: release begin
            if (uploadSigningReady) {
                def uploadSigningConfig = signingConfigs.create("zenModeUpload")
                uploadSigningConfig.storeFile file(uploadSigningEnvironment.storeFile)
                uploadSigningConfig.storePassword uploadSigningEnvironment.storePassword
                uploadSigningConfig.keyAlias uploadSigningEnvironment.keyAlias
                uploadSigningConfig.keyPassword uploadSigningEnvironment.keyPassword
                signingConfig uploadSigningConfig
            } else {
                signingConfig null
            }
            ${MARKER}: release end`;

const TASK_GUARD_REGION = `${MARKER}: task guard begin
def producesReleaseArtifact = { task ->
    def taskName = task.name.toLowerCase()
    task.project == project && taskName.contains("release") &&
        ["assemble", "bundle", "package", "sign", "install"].any { taskName.contains(it) }
}

gradle.taskGraph.whenReady { graph ->
    if (graph.allTasks.any(producesReleaseArtifact)) {
        if (!uploadSigningReady) {
            throw new GradleException("Zen Mode release builds require all five ZEN_MODE_UPLOAD_* signing variables. Debug signing is intentionally unavailable for release artifacts.")
        }
        verifyUploadSigningIdentity()
    }
}
${MARKER}: task guard end`;
const TASK_GUARD_BLOCK = `\n\n${TASK_GUARD_REGION}\n`;

function applyReleaseSigning(contents) {
  if (contents.includes(MARKER)) {
    const regions = [
      {
        name: 'environment',
        begin: `${MARKER}: environment begin`,
        end: `${MARKER}: environment end`,
        replacement: ENVIRONMENT_REGION,
      },
      {
        name: 'release',
        begin: `${MARKER}: release begin`,
        end: `${MARKER}: release end`,
        replacement: RELEASE_SIGNING_BLOCK,
      },
      {
        name: 'task guard',
        begin: `${MARKER}: task guard begin`,
        end: `${MARKER}: task guard end`,
        replacement: TASK_GUARD_REGION,
      },
    ];
    const markerOccurrences = contents.split(MARKER).length - 1;
    const locatedRegions = regions.map((region) => {
      const beginOccurrences = contents.split(region.begin).length - 1;
      const endOccurrences = contents.split(region.end).length - 1;
      const start = contents.indexOf(region.begin);
      const finish = contents.indexOf(region.end);

      if (beginOccurrences !== 1 || endOccurrences !== 1 || start >= finish) {
        throw new Error(
          `Malformed ${region.name} block generated by with-android-release-signing; clean-regenerate Android before building`,
        );
      }

      return { ...region, start, finish: finish + region.end.length };
    });

    if (
      markerOccurrences !== regions.length * 2 ||
      locatedRegions.some((region, index) => index > 0 && locatedRegions[index - 1].finish > region.start)
    ) {
      throw new Error(
        'Malformed blocks generated by with-android-release-signing; clean-regenerate Android before building',
      );
    }

    return locatedRegions.reduceRight(
      (updated, region) =>
        updated.slice(0, region.start) + region.replacement + updated.slice(region.finish),
      contents,
    );
  }

  const signingOccurrences = contents.split(DEBUG_SIGNING_LINE).length - 1;
  if (signingOccurrences !== 2) {
    throw new Error(`Expected two SDK 57 debug-signing assignments, found ${signingOccurrences}`);
  }

  const androidBlock = contents.indexOf('android {');
  const releaseDebugSigning = contents.lastIndexOf(DEBUG_SIGNING_LINE);
  if (androidBlock < 0 || releaseDebugSigning < 0) {
    throw new Error('Could not locate the SDK 57 Android application signing blocks');
  }

  return (
    contents.slice(0, androidBlock) +
    ENVIRONMENT_BLOCK +
    contents.slice(androidBlock, releaseDebugSigning) +
    RELEASE_SIGNING_BLOCK +
    contents.slice(releaseDebugSigning + DEBUG_SIGNING_LINE.length) +
    TASK_GUARD_BLOCK
  );
}

function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (modConfig) => {
    if (modConfig.modResults.language !== 'groovy') {
      throw new Error('Zen Mode release signing requires an Android Groovy build.gradle');
    }
    modConfig.modResults.contents = applyReleaseSigning(modConfig.modResults.contents);
    return modConfig;
  });
}

module.exports = withAndroidReleaseSigning;
module.exports.applyReleaseSigning = applyReleaseSigning;
